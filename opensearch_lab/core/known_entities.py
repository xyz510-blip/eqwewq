def is_trusted_domain(host: str) -> bool:
    """Return True if host belongs to an official allowlisted domain or verified institutional TLD."""
    h = clean_host(host)
    if not h:
        return False
    if h.endswith(OFFICIAL_INSTITUTIONAL_SUFFIXES):
        return True
    apex = extract_registrable_domain(h)
    if h in OFFICIAL_TRUSTED_DOMAINS or apex in OFFICIAL_TRUSTED_DOMAINS:
        return True
    return any(h == dom or h.endswith("." + dom) for dom in OFFICIAL_TRUSTED_DOMAINS)
